%
% Simple cross-platform sleep prevention for long-running MATLAB tasks.
%
% Public API:
%   NoSleep.nosleep_on     - Prevent system sleep (optionally keep display on).
%   NoSleep.nosleep_off    - Release one or all active nosleep requests.
%   NoSleep.with_nosleep   - Execute a function with nosleep enabled.
